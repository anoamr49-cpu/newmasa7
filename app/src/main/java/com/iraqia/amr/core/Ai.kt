    fun answer(q: String): String {
        val t = q.trim().lowercase()
        if (t.isEmpty()) return "اكتب سؤالك يا هندسة وسأجاوبك في الحسابات والمساحة."
        // حاسبة ذكية: مساحة × سمك / أبعاد
        Regex("(\\d+(?:\\.\\d+)?)\\s*[x×*]\\s*(\\d+(?:\\.\\d+)?)").find(t)?.let { m ->
            val a = m.groupValues[1].toDouble(); val b = m.groupValues[2].toDouble()
            val area = a * b
            if (t.contains("خرسان") || t.contains("سق") || t.contains("صبة")) {
                val vol = area * 0.12
                return "سقف ${Fmt.n(a)} × ${Fmt.n(b)} م = مساحة ${Fmt.n(area)} م².\n" +
                        "• حجم الخرسانة (سقف عادي 12 سم) = ${Fmt.n(vol)} م³ (وللفلات سلاب 20 سم = ${Fmt.n(area * 0.20)} م³)\n" +
                        "• حديد التسليح ≈ ${Fmt.n(vol * 85 / 1000, 3)} طن (فلات سلاب ${Fmt.n(area * 0.20 * 115 / 1000, 3)} طن)\n" +
                        "• الإسمنت ≈ ${Fmt.int(Math.ceil(vol * 350 / 1000))} طن (${Fmt.int(Math.ceil(vol * 350 / 1000) * 20)} شيكارة)\n" +
                        "• الزلط ≈ ${Fmt.n(vol * 0.8)} م³ والرمل ≈ ${Fmt.n(vol * 0.4)} م³"
            }
            if (t.contains("محار") || t.contains("بياض")) {
                return "المساحة ${Fmt.n(area)} م² تحتاج: إسمنت ≈ ${Fmt.int(Math.ceil(area * 11 / 50))} شيكارة، ورمل ≈ ${Fmt.n(area * 0.028)} م³."
            }
